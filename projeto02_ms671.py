"""## 6. Construção do Modelo de Atenção + LSTM"""

# Construção do Modelo
# ARQUITETURA (baseada no diagrama do projeto e usando plot_attention_map):
#
#  Entrada one-hot (Tx, n_a)
#       │
#  [Bi-LSTM] n_units_pre unidades  ← camada índice 2
#       │  anotações a^<t>  shape: (Tx, 2*n_units_pre)
#       │
#  Para cada passo t' = 1..Ty:
#    RepeatVector(Tx)(s)            ← camada índice 3
#    Concatenate([a, s_rep])        ← camada índice 4
#    Dense(10, tanh)  → energias e  ← camada índice 5
#    Dense(1, linear) → scores      ← camada índice 6
#    Softmax → α  (atenção)         ← camada índice 7   nome: 'attention_weights'
#    Dot([α, a])  → context         ← camada índice 8
#    [LSTM pós-atenção]             ← camada índice 10
#    Dense(n_y, softmax) → y^<t'>
#
# Note que a ordem e os nomes das camadas foram escolhidos para serem
# compatíveis com a função plot_attention_map.

def construir_modelo(Tx, Ty, n_a, n_y, n_units_pre=32, n_units_post=64):
    """
    Constrói o modelo de tradução com mecanismo de atenção.

    Parâmetros:
        Tx, Ty        : comprimentos das sequências
        n_a, n_y      : tamanhos dos vocabulários
        n_units_pre   : unidades na Bi-LSTM (pré-atenção)
        n_units_post  : unidades na LSTM (pós-atenção)  ← equivale a n_s

    Retorna:
        model : Model Keras compilado
    """


    # Camadas reutilizadas (definidas uma vez, chamadas Ty vezes)
    # A ordem de definição determina o índice das camadas no modelo.

    # Pré-atenção: Bi-LSTM — índice 2 no modelo final
    bilstm = Bidirectional(
        LSTM(n_units_pre, return_sequences=True),
        name='bidirectional_pre_attn'
    )

    # Atenção — índices 3..8
    repeat   = RepeatVector(Tx)                                   # idx 3
    concat   = Concatenate(axis=-1)                               # idx 4
    dense_e1 = Dense(10, activation='tanh',   name='dense_tanh') # idx 5
    dense_e2 = Dense(1,  activation='linear', name='dense_score') # idx 6
    # Softmax sobre o eixo Tx (posições de entrada).
    # Activation('softmax') aplica sobre o último eixo (tamanho 1), gerando aviso.
    # Correçaõ feita com um Lambda que aplica sobre axis=1 (o eixo de comprimento Tx).
    softmax_alpha = Lambda(lambda x: tf.nn.softmax(x, axis=1), name='attention_weights')  # idx 7
    dot_ctx  = Dot(axes=1)                                        # idx 8

    # Pós-atenção: LSTM - índice 10 (índice 9 é ocupado pela concatenação
    # interna do Dot/Reshape; pode variar)
    lstm_post = LSTM(n_units_post, return_state=True, name='post_attn_lstm')

    # Saída
    dense_out = Dense(n_y, activation='softmax', name='saida')


    # Entradas
    X_in = Input(shape=(Tx, n_a),      name='entrada')      # idx 0
    s0   = Input(shape=(n_units_post,), name='s0')            # idx 1 (parte)
    c0   = Input(shape=(n_units_post,), name='c0')


    # Pré-atenção: processa toda a sequência de entrada
    a = bilstm(X_in)   # shape: (batch, Tx, 2*n_units_pre)

    # Estados iniciais da LSTM de pós-atenção
    s = s0
    c = c0


    # Loop de decodificação
    saidas = []

    for t in range(Ty):

        # 1. Repete o estado oculto anterior para cada posição de entrada
        s_rep = repeat(s)                   # (batch, Tx, n_units_post)

        # 2. Concatena com as anotações da Bi-LSTM
        #    Ordem [a, s_rep] — compatível com plot_attention_map (camada 4)
        concat_as = concat([a, s_rep])      # (batch, Tx, 2*n_units_pre + n_units_post)

        # 3. Score de energia
        e = dense_e1(concat_as)             # (batch, Tx, 10)
        e = dense_e2(e)                     # (batch, Tx, 1)

        # 4. Pesos de atenção (softmax sobre Tx)
        alpha = softmax_alpha(e)            # (batch, Tx, 1) — softmax sobre Tx posições

        # 5. Vetor de contexto (soma ponderada das anotações)
        context = dot_ctx([alpha, a])       # (batch, 1, 2*n_units_pre)

        # 6. LSTM de pós-atenção
        s, _, c = lstm_post(context, initial_state=[s, c])

        # 7. Projeção na saída
        y_t = dense_out(s)                  # (batch, n_y)
        saidas.append(y_t)


    # Monta o modelo
    model = Model(inputs=[X_in, s0, c0], outputs=saidas, name='atencao_lstm')

    model.compile(
        optimizer=Adam(learning_rate=0.005),
        loss='categorical_crossentropy',
        metrics=[['accuracy']] * Ty   # uma lista de métricas por saída
    )

    return model


