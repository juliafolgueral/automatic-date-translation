# FUNÇÕES DE PRÉ-PROCESSAMENTO

def string_to_int(string, length, vocab):
    """
    Converte uma string em lista de inteiros usando o vocab fornecido.
    - Padeia com vocab['<pad>'] se a string for curta demais.
    - Trunca se for longa demais.
    - Usa vocab['<unk>'] para caracteres desconhecidos.
    """
    string = string.lower().replace(',', '')

    if len(string) > length:
        string = string[:length]

    rep = [vocab.get(c, vocab.get('<unk>', 0)) for c in string]

    if len(string) < length:
        rep += [vocab['<pad>']] * (length - len(string))

    return rep


def preparar_dataset(dataset, human_vocab, machine_vocab, Tx, Ty):
    """
    Converte todos os pares do dataset em arrays numpy one-hot.

    Retorna:
        X  : (m, Tx, n_a)  — entradas one-hot
        Y  : (m, Ty, n_y)  — saídas one-hot
        Xr : (m, Tx)       — entradas como índices (para to_categorical)
    """
    m   = len(dataset)
    n_a = len(human_vocab)
    n_y = len(machine_vocab)

    X  = np.zeros((m, Tx, n_a),  dtype=np.float32)
    Y  = np.zeros((m, Ty, n_y),  dtype=np.float32)

    for i, (human, machine) in enumerate(dataset):
        # Entrada
        idx_x = string_to_int(human, Tx, human_vocab)
        for t, idx in enumerate(idx_x):
            X[i, t, idx] = 1.0

        # Saída
        idx_y = string_to_int(machine, Ty, machine_vocab)
        for t, idx in enumerate(idx_y):
            Y[i, t, idx] = 1.0

    return X, Y


