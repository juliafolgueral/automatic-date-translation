"""## 7. Funções Auxiliares de Treino e Inferência"""

def saidas_por_passo(Y):
    """Reformata Y de (m, Ty, n_y) para lista de Ty arrays (m, n_y)."""
    return [Y[:, t, :] for t in range(Y.shape[1])]


def estados_zeros(m, n_units_post):
    """Estados iniciais zerados para a LSTM de pós-atenção."""
    return np.zeros((m, n_units_post)), np.zeros((m, n_units_post))


def traduzir(texto, model, human_vocab, inv_machine_vocab,
             Tx, Ty, n_a, n_units_post):
    """
    Traduz uma data do formato humano para o formato máquina (YYYY-MM-DD).
    """
    idx_x  = string_to_int(texto, Tx, human_vocab)
    X_test = np.array([to_categorical(idx_x, num_classes=n_a)])  # (1, Tx, n_a)

    s0, c0 = estados_zeros(1, n_units_post)
    preds  = model.predict([X_test, s0, c0], verbose=0)

    resultado = ''.join(
        inv_machine_vocab[np.argmax(preds[t][0])] for t in range(Ty)
    )
    return resultado

